from pydantic import BaseModel, Field

class ChatRequest(BaseModel):
    user_id: str = Field(..., description="The ID of the user making the request")
    message: str = Field(..., description="The message sent by the user")
    timestamp: str = Field(..., description="The timestamp of the message in ISO 8601 format")

class ChatResponse(BaseModel):
    user_id: str = Field(..., description="The ID of the user receiving the response")
    message: str = Field(..., description="The response message generated by the LLM")
    timestamp: str = Field(..., description="The timestamp of the response in ISO 8601 format")
    model: str = Field(..., description="The model used to generate the response")
    response: str = Field(..., description="The actual response content generated by the LLM")